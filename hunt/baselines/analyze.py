"""Summarize the baseline run -> out/baselines/SUMMARY.md and summary.json. Stdlib + numpy; no model.
Sections: (1) neuron vs random dir vs matched dir vs persona dir vs system prompt, per passing neuron, on HOLDOUT3;
(2) sampling: per-prompt hit rate over 5 samples; (3) null pipeline: finalists passing the paper's rule;
(4) GSM8K accuracy per condition; (5) lens and readout pass-through."""
import json, re, sys
from collections import defaultdict
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent; ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE.parent))
from traits import TRAITS
OUT = ROOT / "out" / "baselines"
T = [k for k in TRAITS if k not in ("coherent", "on_topic", "strange")]


def load(tag):
    gp, jp = OUT / f"{tag}.jsonl", OUT / f"{tag}.judged.jsonl"
    if not gp.exists(): return []
    jud = {}
    if jp.exists():
        for l in jp.read_text().splitlines():
            r = json.loads(l)
            if "jev" in r: jud[(r["id"], r["i"])] = r["jev"]
    rows = []
    for l in gp.read_text().splitlines():
        g = json.loads(l); g["jev"] = jud.get((g["id"], g["i"])); rows.append(g)
    return rows


def by_id(rows):
    d = defaultdict(list)
    for r in rows:
        if r["jev"]: d[r["id"]].append(r)
    return d


def P(rs, t): return float(np.mean([r["jev"][t] for r in rs])) if rs else float("nan")


def boot(a, b, reps=4000, rng=np.random.default_rng(1)):
    a, b = np.array(a), np.array(b)
    ds = [rng.choice(a, len(a)).mean() - rng.choice(b, len(b)).mean() for _ in range(reps)]
    return float(np.percentile(ds, 2.5)), float(np.percentile(ds, 97.5))


S = {}; L = ["# Baseline run summary (generated by hunt/baselines/analyze.py)\n"]
main = by_id(load("main"))
if main:
    ctrl_rows = [r for k, v in main.items() if k.startswith("ctrl_") for r in v]
    L += ["## 1. Neuron vs direction baselines on HOLDOUT3 (dose 0.75, top trait fixed to the paper's)\n",
          "| neuron | trait | neuron P | hits | coh | reversed P | random dir P (3) | matched dir P (3) | persona dir P @.5/.75/1 (coh) | system prompt P (coh) | ctrl P |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    S["main"] = []
    for k, rs in sorted(main.items()):
        if not k.startswith("neuron_") or k.endswith(f"@-0.75"): continue
        m = rs[0]["meta"]; t = m["top"]; nid = k[len("neuron_"):-len("@0.75")]
        rev = main.get(f"neuron_{nid}@-0.75", []); rnd = [P(main.get(f"randdir_{nid}_s{s}", []), t) for s in range(3)]
        mat = [P(main.get(f"matched_{nid}_s{s}", []), t) for s in range(3)]
        pdir = [(P(main.get(f"personadir_{m['persona']}_L{m['neuron'][0]}@{d}", []), t), P(main.get(f"personadir_{m['persona']}_L{m['neuron'][0]}@{d}", []), "coherent")) for d in (0.5, 0.75, 1.0)]
        sysr = main.get(f"system_{m['persona']}", [])
        rec = dict(id=nid, trait=t, P=P(rs, t), hits=sum(r["jev"][t] >= .5 for r in rs), n=len(rs), coherent=P(rs, "coherent"), on_topic=P(rs, "on_topic"),
                   reversed=P(rev, t), random_dir=rnd, matched_dir=mat, persona_dir=pdir, system=(P(sysr, t), P(sysr, "coherent")), ctrl=P(ctrl_rows, t),
                   ci=boot([r["jev"][t] for r in rs], [r["jev"][t] for r in ctrl_rows]) if ctrl_rows else None)
        S["main"].append(rec)
        f = lambda x: "n/a" if x != x else f"{x:.2f}"
        L.append(f"| {nid} | {t} | {f(rec['P'])} | {rec['hits']}/{rec['n']} | {f(rec['coherent'])} | {f(rec['reversed'])} | {' '.join(map(f, rnd))} | {' '.join(map(f, mat)) if mat and mat[0] == mat[0] else 'n/a'} | {' / '.join(f'{f(p)} ({f(c)})' for p, c in pdir)} | {f(rec['system'][0])} ({f(rec['system'][1])}) | {f(rec['ctrl'])} |")
    L.append(f"\nControl rows: {len(ctrl_rows)}; mean control coherence {P(ctrl_rows, 'coherent'):.2f}.\n")
samp = by_id(load("sample"))
if samp:
    L += ["## 2. Sampling at temperature 0.7, 5 samples per prompt\n", "| neuron | trait | mean P | per-prompt hit rate (mean over samples) | prompts with >=3/5 hits | coh |", "|---|---|---|---|---|---|"]
    S["sample"] = []
    groups = defaultdict(list)
    for k, rs in samp.items():
        if k.startswith("sample_") and not k.startswith("sample_baseline"): groups[k.rsplit("_s", 1)[0]] += rs
    for k, rs in sorted(groups.items()):
        t = rs[0]["meta"]["top"]; byp = defaultdict(list)
        for r in rs: byp[r["i"]].append(r["jev"][t] >= .5)
        rates = [np.mean(v) for v in byp.values()]
        rec = dict(id=k, trait=t, P=P(rs, t), hit_rate=float(np.mean(rates)), prompts_majority=int(sum(np.mean(v) >= .6 for v in byp.values())), n_prompts=len(byp), coherent=P(rs, "coherent"))
        S["sample"].append(rec)
        L.append(f"| {k} | {t} | {rec['P']:.2f} | {rec['hit_rate']:.2f} | {rec['prompts_majority']}/{rec['n_prompts']} | {rec['coherent']:.2f} |")
nullc = by_id(load("null_confirm"))
if nullc:
    L += ["## 3. Null pipeline: 100 random neurons screened, top 8 confirmed on HOLDOUT, paper's rule applied\n", "| finalist | screen best | top trait @.75 | P | dP [CI] | coh | passes rule |", "|---|---|---|---|---|---|---|"]
    ctrl = [r for k, v in nullc.items() if k.startswith("nullctrl") for r in v]; npass = 0; S["null"] = []
    for k, rs in sorted(nullc.items()):
        if not k.endswith("@0.75") or k.startswith("nullctrl"): continue
        Pm = {t: P(rs, t) for t in T}; top = max(Pm, key=Pm.get); lo, hi = boot([r["jev"][top] for r in rs], [r["jev"][top] for r in ctrl]) if ctrl else (float("nan"), float("nan"))
        ok = Pm[top] >= .5 and lo > 0 and P(rs, "coherent") >= .6; npass += ok
        S["null"].append(dict(id=k, top=top, P=Pm[top], ci=(lo, hi), coherent=P(rs, "coherent"), passes=bool(ok)))
        L.append(f"| {k} | {rs[0]['meta'].get('screen_best')} {rs[0]['meta'].get('screen_p', 0):.2f} | {top} | {Pm[top]:.2f} | {Pm[top] - P(ctrl, top):.2f} [{lo:.2f}, {hi:.2f}] | {P(rs, 'coherent'):.2f} | {'YES' if ok else 'no'} |")
    L.append(f"\n**{npass} of {sum(1 for k in nullc if k.endswith('@0.75') and not k.startswith('nullctrl'))} null finalists pass the rule.**\n"); S["null_pass"] = npass
cap = load("capability")
if cap:
    gold = [json.loads(l) for l in (OUT / "data" / "gsm8k_test.jsonl").read_text().splitlines() if l.strip()][:50]
    ans = [re.sub(r"[^0-9.-]", "", g["answer"].split("####")[-1]) for g in gold]
    L += ["## 4. GSM8K (first 50 test problems), exact-match accuracy\n", "| condition | correct/50 |", "|---|---|"]; S["capability"] = {}
    byc = defaultdict(list)
    for r in cap: byc[r["id"]].append(r)
    for k, rs in sorted(byc.items()):
        c = 0
        for r in rs:
            m = re.findall(r"Answer:\s*\$?(-?[0-9][0-9,]*\.?[0-9]*)", r["output"]) or re.findall(r"(-?[0-9][0-9,]*\.?[0-9]*)", r["output"])
            pred = m[-1].replace(",", "").rstrip(".") if m else ""
            c += pred == ans[r["i"]].rstrip(".")
        S["capability"][k] = c; L.append(f"| {k} | {c}/{len(rs)} |")
for name in ("lens", "readout"):
    p = OUT / f"{name}.json"
    if p.exists(): S[name] = json.loads(p.read_text()); L.append(f"\n## {name}: see out/baselines/{name}.json\n")
(OUT / "SUMMARY.md").write_text("\n".join(L) + "\n"); (OUT / "summary.json").write_text(json.dumps(S, indent=1))
print("\n".join(L[:60]))
